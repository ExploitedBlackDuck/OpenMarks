import { readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { resolve } from 'node:path';

const folder = resolve('demo-vault/_openmarks/bookmarks');
const files = (await readdir(folder)).filter((name) => name.endsWith('.md')).sort();
const samples = [];
const scalar = (frontmatter, key) => {
  const match = frontmatter.match(new RegExp(`^${key}:\\s*(.*)$`, 'm'));
  if (!match) return '';
  const value = match[1].trim();
  try { return JSON.parse(value); } catch { return value; }
};
for (const name of files) {
  const content = await readFile(resolve(folder, name), 'utf8');
  const match = content.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) throw new Error(`Invalid frontmatter in ${name}`);
  const [, fm, body] = match;
  const tags = [...fm.matchAll(/^\s+-\s*(.+)$/gm)].map((item) => {
    try { return JSON.parse(item[1]); } catch { return item[1].trim().replace(/^['"]|['"]$/g, ''); }
  });
  samples.push({
    id: scalar(fm, 'id'), title: scalar(fm, 'title'), url: scalar(fm, 'url'),
    description: scalar(fm, 'description'), collection: scalar(fm, 'collection'), tags,
    favorite: scalar(fm, 'favorite') === true || scalar(fm, 'favorite') === 'true',
    status: scalar(fm, 'status') || 'unread', created: scalar(fm, 'created'), notes: body.trim(),
  });
}
if (samples.length !== 100) throw new Error(`Expected 100 sample bookmarks, found ${samples.length}`);
const expectedCounts = {
  'Technology & Development': 15, 'Cybersecurity & Privacy': 15, 'Science & Research': 15,
  'Education & Learning': 15, 'Books & Reference': 10, 'News & Media': 10,
  'Productivity & Tools': 10, 'Culture & Museums': 10,
};
const counts = Object.fromEntries(Object.keys(expectedCounts).map((key) => [key, 0]));
const urls = new Set();
for (const item of samples) {
  if (!item.id || !item.title || !item.url || !item.description || !item.collection || !item.tags.length || !item.created) throw new Error(`Missing required bookmark metadata: ${item.title || item.url || '(unknown)'}`);
  const parsed = new URL(item.url);
  if (!['http:', 'https:'].includes(parsed.protocol) || parsed.username || parsed.password) throw new Error(`Unsafe URL: ${item.url}`);
  if (parsed.search || parsed.hash) throw new Error(`Tracking or fragment parameters are not allowed: ${item.url}`);
  const normalized = `${parsed.protocol}//${parsed.host}${parsed.pathname.replace(/\/$/, '') || '/'}`.toLowerCase();
  if (urls.has(normalized)) throw new Error(`Duplicate normalized URL: ${item.url}`);
  urls.add(normalized);
  const category = item.collection.split('/')[0];
  if (!(category in counts)) throw new Error(`Unexpected category: ${category}`);
  counts[category]++;
  if (/\b(?:faith|catholic|vatican|new advent|ignatius press|usccb)\b/i.test([item.title, item.description, item.collection, ...item.tags].join(' '))) throw new Error(`Religious demonstration bookmark remains: ${item.title}`);
}
for (const [category, expected] of Object.entries(expectedCounts)) if (counts[category] !== expected) throw new Error(`${category}: expected ${expected}, found ${counts[category]}`);
const encoded = gzipSync(Buffer.from(JSON.stringify(samples)), { level: 9 }).toString('base64');
const target = resolve('src/sample-data-generated.ts');
await writeFile(target, `// Generated by scripts/generate-sample-data.mjs.\nexport const SAMPLE_DATA_GZIP_BASE64 = ${JSON.stringify(encoded)};\n`, 'utf8');
await rm(resolve('sample-data.json'), { force: true });
console.log(`Generated ${samples.length} compressed, lazy-loaded sample bookmarks in ${target}`);
